"""Build the OpenAMRobot platform model files from upstream, and check them.

    python build.py build --upstream ~/p79/src/openamr-platform-sw     (WSL, ROS 2 Jazzy: needs `xacro`)
    python build.py --check                                            (anywhere: manifest matches the files)

Nothing is drawn or edited here. The URDF is upstream's own xacro, expanded by upstream's tool; the meshes are copied
byte for byte; NOTICE.md and LICENSING.md are upstream's own files. The upstream checkout is only read. The manifest
records where every file came from (repository, commit) and under which licence, as upstream's NOTICE.md states it.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DESC = "ros2/src/openamrobot_description"
REPO = "openAMRobot/openamr-platform-sw"
LICENSE = "CERN-OHL-P-2.0"
NOTICE = (
    "Upstream NOTICE.md (kept beside the files): the URDF/xacro and the chassis meshes are CAD-derived robot geometry "
    "under CERN-OHL-P-2.0, rights assigned to OpenAMRobot (Botshare LTD); the vendor-component meshes are envelopes "
    "generated by MIT-licensed code, no vendor CAD is redistributed. The names OpenAMRobot and OpenAMR are not "
    "licensed and imply no endorsement."
)


def sha(b: bytes) -> str:
    return "sha256:" + hashlib.sha256(b).hexdigest()


def git(up: Path, *args: str) -> str:
    run = subprocess.run(["git", "-C", str(up), *args], capture_output=True, text=True, check=True)  # noqa: S607
    return run.stdout.strip()


def build(up: Path) -> None:
    if git(up, "status", "--porcelain", "--", DESC):
        sys.exit(f"{DESC} has local changes in {up}: refusing to import a model that is not a commit")
    commit = git(up, "rev-parse", "HEAD")
    xacro = up / DESC / "urdf/robo_urdf.urdf.xacro"
    run = subprocess.run(["xacro", str(xacro)], capture_output=True, check=True, cwd=xacro.parent)  # noqa: S607
    expanded = run.stdout
    refs = sorted(set(re.findall(rb'filename="package://openamrobot_description/([^"]+\.stl)"', expanded)))
    files: dict[str, bytes] = {"robo_urdf.urdf": expanded}
    for r in refs:
        rel = r.decode()
        files[rel] = (up / DESC / rel).read_bytes()
    out = HERE
    for rel, data in files.items():
        (out / rel).parent.mkdir(parents=True, exist_ok=True)
        (out / rel).write_bytes(data)
    shutil.copyfile(up / "NOTICE.md", out / "NOTICE.md")
    shutil.copyfile(up / "LICENSING.md", out / "LICENSING.md")
    shutil.copyfile(up / DESC / "meshes/PROVENANCE.yaml", out / "PROVENANCE.yaml")
    stl_all = sorted(
        p.relative_to(up / DESC).as_posix() for p in (up / DESC / "meshes").rglob("*") if p.suffix.lower() == ".stl"
    )
    omitted = [
        {
            "path": f"{DESC}/{p}",
            "reason": "not referenced by the expanded URDF (collision geometry is primitives there)",
        }
        for p in stl_all
        if p not in {r.decode() for r in refs}
    ]
    manifest = {
        "slug": "openamrobot-platform",
        "name": "OpenAMRobot platform base",
        "urdf": "robo_urdf.urdf",
        "files": [{"path": p, "sha256": sha(d)} for p, d in sorted(files.items())],
        "source": {
            "repository": REPO,
            "commit": commit,
            "path": f"{DESC}/urdf/robo_urdf.urdf.xacro",
            "license_spdx": LICENSE,
            "notice": NOTICE,
            "note": "URDF expanded with xacro from the file named in path; "
            "meshes copied unchanged from the same commit.",
        },
        "omitted": omitted,
    }
    (out / "manifest.json").write_text(
        json.dumps(manifest, indent=1, sort_keys=True) + "\n", encoding="utf-8", newline="\n"
    )
    print(f"model from {REPO}@{commit[:10]}: {len(files)} files, {len(omitted)} upstream meshes not stored")


def check() -> int:
    m = json.loads((HERE / "manifest.json").read_text(encoding="utf-8"))
    bad = []
    for f in m["files"]:
        p = HERE / f["path"]
        if not p.is_file() or sha(p.read_bytes()) != f["sha256"]:
            bad.append(f["path"])
    for extra in ("NOTICE.md", "LICENSING.md", "PROVENANCE.yaml"):
        if not (HERE / extra).is_file():
            bad.append(extra)
    print("model files match the manifest" if not bad else f"MISMATCH: {bad}")
    return 1 if bad else 0


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", nargs="?", choices=["build"])
    ap.add_argument("--upstream", type=Path)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if a.check or not a.cmd:
        sys.exit(check())
    if a.upstream is None:
        sys.exit("--upstream is required")
    build(a.upstream.expanduser())


if __name__ == "__main__":
    main()
